            const vlxTrack = document.getElementById("vlxTrack");
            const vlxCards = document.querySelectorAll(".vlx-card");
            
            const nextBtn = document.getElementById("vlxNextBtn");
            const prevBtn = document.getElementById("vlxPrevBtn");
            
            let currentIndex = 0;
            
            function getCardsPerView() {
            
                if(window.innerWidth < 768){
                    return 2;
                }
                else if(window.innerWidth < 1200){
                    return 3;
                }
                else{
                    return 6;
                }
            
            }
            
            function updateSlider(){
            
                const cardsPerView = getCardsPerView();
            
                const cardWidth = vlxCards[0].offsetWidth + 20;
            
                const maxIndex = vlxCards.length - cardsPerView;
            
                if(currentIndex > maxIndex){
                    currentIndex = maxIndex;
                }
            
                if(currentIndex < 0){
                    currentIndex = 0;
                }
            
                vlxTrack.style.transform =
                    `translateX(-${currentIndex * cardWidth}px)`;
            
            }
            
            nextBtn.addEventListener("click", () => {
            
                const cardsPerView = getCardsPerView();
            
                if(currentIndex < vlxCards.length - cardsPerView){
                    currentIndex++;
                    updateSlider();
                }
            
            });
            
            prevBtn.addEventListener("click", () => {
            
                if(currentIndex > 0){
                    currentIndex--;
                    updateSlider();
                }
            
            });
            
            window.addEventListener("resize", updateSlider);
            
            updateSlider();
            
         </script>
